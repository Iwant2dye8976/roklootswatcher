export function formatSpeedupMinutes(
  mins: number,
  unit: SpeedupUnit,
  lang: AppLanguage = "en"
): string {
  if (!mins || mins <= 0) return "0m";
  if (unit === "days") {
    const d = mins / 1440;
    return `${d.toFixed(d >= 10 ? 1 : 2)}d`;
  }
  if (unit === "minutes") {
    return `${Math.round(mins).toLocaleString()}${lang === "vi" ? "p" : "m"}`;
  }
  if (unit === "dhm") {
    const total = Math.round(mins);
    const days = Math.floor(total / 1440);
    const rem = total % 1440;
    const hours = Math.floor(rem / 60);
    const m = rem % 60;
    if (days > 0) return `${days}d ${hours}h ${m}m`;
    if (hours > 0) return `${hours}h ${m}m`;
    return `${m}m`;
  }
  const h = mins / 60;
  return `${h.toFixed(1)}h`;
}

export function useI18n(lang: AppLanguage) {
  const dict = translations[lang] || translations.en;
  return {
    t: (key: keyof typeof translations.en) => dict[key] || translations.en[key] || key,
    dict,
  };
}
